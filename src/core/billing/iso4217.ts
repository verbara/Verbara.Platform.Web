/**
 * The canonical form of a currency the user typed: trimmed and upper-cased when that is an active
 * ISO 4217 alphabetic code, else `null`.
 */
export function canonicalCurrency(input: string): string | null {
  const code = input.trim().toUpperCase();
  return ISO_4217_CODES.has(code) ? code : null;
}
